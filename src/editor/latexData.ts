/** Base de comandos e ambientes para autocomplete (TL-304). `pkg` vazio = LaTeX core. */

export interface CommandDef {
  name: string
  /** Assinatura com placeholders: `[opção]{texto}`. */
  sig: string
  doc: string
  pkg: string
}

export interface EnvDef {
  name: string
  doc: string
  pkg: string
  /** Argumentos logo após `\begin{nome}`, ex.: `{cols}`. */
  args?: string
}

type Row = [name: string, sig: string, doc: string]

const make = (pkg: string, rows: Row[]): CommandDef[] =>
  rows.map(([name, sig, doc]) => ({ name, sig, doc, pkg }))

