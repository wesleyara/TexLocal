/** Converte `[opção]{arg}` em snippet do CodeMirror: `[${opção}]{${arg}}`. */
export function signatureToSnippet(name: string, sig: string): string {
  let n = 0
  const body = sig.replace(/([[{])([^\]}]*)([\]}])/g, (_m, open, label, close) => {
    n += 1
    return `${open}\${${n}:${label}}${close}`
  })
  return `\\${name}${body}`
}
